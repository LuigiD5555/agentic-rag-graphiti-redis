#!/bin/bash
# Example workflow for identifying unused functions/methods/classes
# and generating a CSV report with detailed information

echo "=== Unused Code Detection Workflow ==="
echo ""
echo "This script demonstrates how to:"
echo "1. Run E2E tests with coverage"
echo "2. Export coverage data to JSON"
echo "3. Generate a CSV report of unused symbols"
echo ""

# Step 1: Run E2E tests with coverage (example)
echo "Step 1: Running E2E tests with coverage..."
echo "Note: Adjust this command based on your test runner"
echo ""
echo "Example:"
echo "  coverage run -m pytest -q tests/e2e/  # Run your E2E tests"
echo "  # Or use your ingestion pipeline:"
echo "  # python tools/debug/coverage/run_ingestion_with_coverage.py ."
echo ""

# Step 2: Export coverage to JSON
echo "Step 2: Exporting coverage data to JSON..."
echo "coverage json -o coverage.json"
echo ""

# Step 3: Generate CSV report of unused symbols
echo "Step 3: Generating CSV report of unused symbols..."
echo "python tools/debug/coverage/unused_symbols_from_coverage.py \\"
echo "  --repo-root . \\"
echo "  --coverage-json coverage.json \\"
echo "  --out unused_symbols_report.md \\"
echo "  --format csv"
echo ""

# Alternative: Generate both markdown and CSV
echo "Alternative: Generate both markdown and CSV reports..."
echo "python tools/debug/coverage/unused_symbols_from_coverage.py \\"
echo "  --repo-root . \\"
echo "  --coverage-json coverage.json \\"
echo "  --out unused_symbols_report.md \\"
echo "  --format both \\"
echo "  --csv-out unused_symbols_detailed.csv"
echo ""

echo "=== CSV Report Fields ==="
echo ""
echo "The CSV report includes the following fields:"
echo "1. file_path - Location in the directory"
echo "2. qualified_name - Fully qualified name (e.g., MyClass.my_method)"
echo "3. kind - Type (function/method/class)"
echo "4. start_line, end_line, line_range - Line numbers where located"
echo "5. code_snippet - Actual code (truncated if too long)"
echo "6. intended_function - What the function is supposed to do (based on name)"
echo "7. suggestion - Action recommendation:"
echo "   - 'consider_delete' - Likely safe to delete"
echo "   - 'investigate' - Needs manual review"
echo "   - 'keep' - Should be kept (abstract methods, core dunder methods)"
echo "8. notes - Additional context (dunder, property, abstractmethod, etc.)"
echo "9. executed_lines, total_lines, coverage_ratio - Coverage statistics"
echo "10. is_async, is_dunder, decorators - Technical details"
echo ""

echo "=== Analysis Workflow ==="
echo ""
echo "After generating the CSV:"
echo "1. Open the CSV in a spreadsheet program or text editor"
echo "2. Filter by 'suggestion' column to prioritize review"
echo "3. Review 'consider_delete' items first"
echo "4. Check 'intended_function' to understand purpose"
echo "5. Examine 'code_snippet' to verify if code is actually unused"
echo "6. Use 'notes' column for additional context"
echo "7. Make decisions: delete, keep, or refactor"
echo ""

echo "=== Example Commands ==="
echo ""
echo "# Generate CSV only"
echo "python tools/debug/coverage/unused_symbols_from_coverage.py \\"
echo "  --repo-root . \\"
echo "  --coverage-json tools/debug/coverage/coverage_reports/coverage.json \\"
echo "  --out unused_analysis.csv \\"
echo "  --format csv"
echo ""
echo "# Generate both reports"
echo "python tools/debug/coverage/unused_symbols_from_coverage.py \\"
echo "  --repo-root . \\"
echo "  --coverage-json coverage.json \\"
echo "  --out report.md \\"
echo "  --format both \\"
echo "  --csv-out detailed_analysis.csv"
echo ""
echo "# View CSV in terminal (first 10 lines)"
echo "head -n 11 detailed_analysis.csv | column -t -s,"
echo ""
echo "# Count suggestions"
echo "cut -d, -f8 detailed_analysis.csv | sort | uniq -c"
echo ""